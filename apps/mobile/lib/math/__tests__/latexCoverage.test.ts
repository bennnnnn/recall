/**
 * Every command MathJax knows, and every dialect command the renderers
 * rewrite, drawn both ways: the native renderer (inline maths, and display
 * maths' fallback) must place it without printing source or a name it does not
 * know, and MathJax (display maths) must never paint a backslash for it.
 *
 * The list is published as docs/fixtures/latex_commands.json so the API can
 * hold its replies to what the phone draws. `pnpm latex-symbols` rewrites it.
 */
import { DIALECT_COMMANDS, EXTRA_OPERATOR_NAMES } from "@/lib/math/latexDialects";
import { findLatexLeaks } from "@/lib/math/latexLeaks";
import { subscribeUnknownLatexCommands } from "@/lib/math/latexNames";
import { LATEX_OPERATOR_NAMES, LATEX_SYMBOLS } from "@/lib/math/latexSymbols.generated";
import { latexToSvgMath } from "@/lib/math/svgMath";
import { parseSimpleLatex, segmentsToPlain } from "@/lib/math/text";
import { mathJaxCommands } from "@/lib/math/__tests__/mathJaxTables";

// The lib test project has Jest types but no Node types (see licenses.test.ts).
declare const __dirname: string;
declare const process: { env: Record<string, string | undefined> };
const { readFileSync, writeFileSync } = jest.requireActual<{
  readFileSync(path: string, encoding: "utf8"): string;
  writeFileSync(path: string, data: string): void;
}>("node:fs");
const { join } = jest.requireActual<{ join(...parts: string[]): string }>("node:path");

const FIXTURE = join(__dirname, "..", "..", "..", "..", "..", "docs", "fixtures", "latex_commands.json");

const { commands: MATHJAX_COMMANDS, environments: ENVIRONMENTS } = mathJaxCommands();
const COMMANDS = [...new Set([...MATHJAX_COMMANDS, ...DIALECT_COMMANDS])].sort();

/** Commands whose arguments are not braced groups. */
const SAMPLES: Readonly<Record<string, string>> = {
  verb: "\\verb|x+1|",
  def: "\\def\\twice#1{#1#1}",
  let: "\\let\\twice=\\alpha",
  begin: "\\begin{matrix}a & b\\end{matrix}",
  end: "\\begin{matrix}a & b\\end{matrix}",
  root: "\\root 3 \\of {x}",
  not: "a \\not\\in B",
  left: "\\left( x \\right)",
  right: "\\left( x \\right)",
  middle: "\\left( x \\middle| y \\right)",
  over: "{a \\over b}",
  atop: "{a \\atop b}",
  above: "{a \\above 1pt b}",
  choose: "{n \\choose k}",
  brace: "{n \\brace k}",
  brack: "{n \\brack k}",
  overwithdelims: "{a \\overwithdelims() b}",
  atopwithdelims: "{a \\atopwithdelims() b}",
  abovewithdelims: "{a \\abovewithdelims() 1pt b}",
  unicode: "\\unicode{x2192}",
  SI: "\\SI{9.8}{\\meter\\per\\second\\squared}",
  qty: "\\qty{9.8}{m/s^2}",
};

/** A literal backslash, asked for by name, is the one thing MathJax may paint. */
const PAINTS_A_BACKSLASH = new Set(["textbackslash"]);

function sample(name: string): string {
  return SAMPLES[name] ?? `\\${name}{a}{b}{c}{d}{e}{f}`;
}

/** Source the native renderer would show for `latex`, and names it could not place. */
function nativeProblems(latex: string): string[] {
  const unknown: string[] = [];
  const unsubscribe = subscribeUnknownLatexCommands((name) => unknown.push(name));
  const plain = segmentsToPlain(parseSimpleLatex(latex));
  unsubscribe();
  return [
    ...findLatexLeaks(plain).map((leak) => `shows ${JSON.stringify(leak.text)} in ${JSON.stringify(plain)}`),
    ...unknown.map((name) => `cannot place \\${name}`),
  ];
}

describe("every LaTeX command the phone draws", () => {
  it.each(COMMANDS)("\\%s renders natively with no source", (name) => {
    expect(nativeProblems(sample(name))).toEqual([]);
  });

  it.each(ENVIRONMENTS)("the %s environment renders natively with no source", (env) => {
    expect(nativeProblems(`\\begin{${env}}{cc}a & b \\\\ c & d\\end{${env}}`)).toEqual([]);
  });

  it.each(COMMANDS.filter((name) => !PAINTS_A_BACKSLASH.has(name)))(
    "\\%s never makes MathJax paint a backslash",
    async (name) => {
      const svg = (await latexToSvgMath(sample(name), true))?.svg ?? "";
      expect(svg.includes('data-c="5C"')).toBe(false);
    },
  );

  it("is published for the API (run `pnpm latex-symbols` to update)", () => {
    const fixture = `${JSON.stringify(
      {
        about:
          "Every LaTeX command the phone draws: inline by its native renderer, display maths by " +
          "MathJax. Generated by apps/mobile/lib/math/__tests__/latexCoverage.test.ts.",
        symbols: Object.fromEntries(Object.keys(LATEX_SYMBOLS).sort().map((name) => [name, LATEX_SYMBOLS[name]])),
        operators: [...new Set([...Object.keys(LATEX_OPERATOR_NAMES), ...Object.keys(EXTRA_OPERATOR_NAMES)])].sort(),
        commands: COMMANDS.filter((name) => !(name in LATEX_SYMBOLS) && !(name in LATEX_OPERATOR_NAMES)),
        environments: ENVIRONMENTS,
      },
      null,
      2,
    )}\n`;
    if (process.env.UPDATE_LATEX_SYMBOLS) writeFileSync(FIXTURE, fixture);
    expect(readFileSync(FIXTURE, "utf8")).toBe(fixture);
  });
});
