def test_about_the_y_axis_the_ends_are_level_circles() -> None:
    graph = _plot(
        "The region under y = x² from x = 0 to x = 2 is rotated about the y-axis. Sketch the "
        "region and the solid.",
        _curve("f", "x^2"),
        _shade("f", "x-axis", "0", "2"),
        {"item": "axis", "line": "y-axis"},
        _SOLID,
    )
    mirror, *ends = _mirrors(graph)
    assert min(x for x, _ in mirror) == pytest.approx(-2, abs=1e-3)
    # The base at y = 0 and the rim at y = 4, each of radius 2 across the y-axis.
    assert len(ends) == 2
    for end in ends:
        xs = [x for x, _ in end]
        assert (min(xs), max(xs)) == pytest.approx((-2, 2), abs=1e-3)


_U5_083 = (
    "Find the volume of the solid of revolution about the y-axis generated by revolving the "
    "region enclosed by the curve x = √y and the y-axis from y = 0 to y = 4. Sketch the "
    "region and the solid."
)


def test_a_region_along_y_stands_on_the_interval_of_y_it_states() -> None:
    graph = _plot(
        _U5_083,
        {"item": "curve", "name": "f", "x": "sqrt(y)", "domain": ["0", "4"]},
        {"item": "shade", "between": ["f", "y-axis"], "from": "0", "to": "4", "wrt": "y"},
        {"item": "axis", "line": "y-axis"},
        _SOLID,
    )
    assert graph is not None
    shade = next(r for r in graph.regions if r.kind == "shade")
    assert (min(y for _, y in shade.points), max(y for _, y in shade.points)) == pytest.approx(
        (0, 4), abs=1e-3
    )
    mirror, *ends = _mirrors(graph)
    assert min(x for x, _ in mirror) == pytest.approx(-2, abs=1e-3)
    assert len(ends) == 1  # the rim at y = 4, radius 2; the tip at the origin has none


