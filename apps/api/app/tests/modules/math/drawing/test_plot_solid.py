"""The solid a shaded region sweeps about its axis, sketched from the checked region."""

from __future__ import annotations

from typing import Any

import pytest

from app.modules.math.schemas.plot import PlotGraphSpec
from app.tests.modules.math.drawing.test_plot_review import _curve, _plot, _shade

_AXIS = {"item": "axis", "line": "x-axis"}
_SOLID = {"item": "solid"}


def _mirrors(graph: PlotGraphSpec | None) -> list[list[tuple[float, float]]]:
    assert graph is not None
    return [region.points for region in graph.regions if region.kind == "mirror"]


def _across(points: list[tuple[float, float]]) -> tuple[float, float]:
    return min(y for _, y in points), max(y for _, y in points)


def test_a_disc_region_gets_its_mirror_and_its_end_circle() -> None:
    graph = _plot(
        "The region under y = x² from x = 0 to x = 2 is rotated about the x-axis. Sketch the "
        "region and the solid.",
        _curve("f", "x^2"),
        _shade("f", "x-axis", "0", "2"),
        _AXIS,
        _SOLID,
    )
    mirror, *ends = _mirrors(graph)
    # The region turned over: y from -4 to 0.
    assert _across(mirror) == pytest.approx((-4, 0), abs=1e-3)
    # One end circle, at x = 2 with radius 4 (the tip at 0 has none).
    assert len(ends) == 1
    assert _across(ends[0]) == pytest.approx((-4, 4), abs=1e-3)
    xs = [x for x, _ in ends[0]]
    assert min(xs) < 2 < max(xs)


def test_a_washer_s_end_has_its_hole() -> None:
    graph = _plot(
        "The region between y = x + 2 and y = 1 from x = 0 to x = 2 is rotated about the "
        "x-axis. Sketch the region and the solid.",
        _curve("f", "x + 2"),
        {"item": "line", "name": "L", "y": "1"},
        _shade("f", "L", "0", "2"),
        _AXIS,
        _SOLID,
    )
    _mirror, *ends = _mirrors(graph)
    radii = sorted(_across(end)[1] for end in ends)
    assert radii == pytest.approx([1, 1, 2, 4], abs=1e-3)


def test_parts_on_either_side_of_the_axis_each_sweep_their_own() -> None:
    graph = _plot(
        "The region between y = x³, the x-axis and the lines x = −1 and x = 2 is rotated "
        "about the x-axis. Sketch the region and the solid.",
        _curve("f", "x^3"),
        _shade("f", "x-axis", "-1", "2"),
        _AXIS,
        _SOLID,
    )
    assert len(_mirrors(graph)) == 4  # two mirrors, a circle at each end


@pytest.mark.parametrize(
    ("items"),
    [
        # No axis the question names: no solid.
        [_curve("f", "x^2"), _shade("f", "x-axis", "0", "2"), _SOLID],
        # No region: nothing to turn.
        [_curve("f", "x^2"), _AXIS, _SOLID],
    ],
)
def test_no_solid_without_its_region_and_axis(items: list[dict[str, Any]]) -> None:
    graph = _plot(
        "The region under y = x² from x = 0 to x = 2 is rotated about the x-axis.", *items
    )
    assert graph is not None and not _mirrors(graph)


