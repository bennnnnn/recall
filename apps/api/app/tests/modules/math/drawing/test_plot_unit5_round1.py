from app.modules.math.figure.revolution import revolves_into
from app.tests.modules.math.drawing.test_plot_review import _curve, _plot, _shade


def test_a_region_between_found_places_inside_a_stated_interval_is_left_out() -> None:
    """u5-051: "from x = -4 to x = 3" shaded between the roots ±2 only."""
    question = (
        "Find the area of the region enclosed by the graph of f(x) = 12 − 3x² and the "
        "x-axis from x = −4 to x = 3. Draw the graph and shade the region."
    )
    roots = _plot(question, _curve("f", "12 - 3x^2"), _shade("f", "x-axis", "-2", "2"))
    assert roots is not None and not roots.regions
    whole = _plot(question, _curve("f", "12 - 3x^2"), _shade("f", "x-axis", "-4", "3"))
    assert whole is not None and len(whole.regions) == 3


@pytest.mark.parametrize(
    ("shape", "question", "sweeps"),
    [
        (
            "cylinder",
            "Find the volume of the solid of revolution about the y-axis generated by revolving "
            "the region enclosed by the curve x = √y and the y-axis from y = 0 to y = 4. "
            "Sketch the region and the solid.",
            False,
        ),
        ("cylinder", "Revolve the region under y = 3 from x = 0 to x = 2 about the x-axis.", True),
        ("cone", "Revolve the region under y = 2x from x = 0 to x = 3 about the x-axis.", True),
        ("cone", "Revolve the region under y = x + 1 from x = 0 to x = 2 about the x-axis.", False),
        (
            "frustum",
            "Revolve the region under y = x + 1 from x = 0 to x = 2 about the x-axis.",
            True,
        ),
        ("sphere", "Revolve the region under y = √(4 − x²) about the x-axis.", True),
        ("sphere", "Show that the volume of a sphere of radius r is (4/3)πr³.", True),
    ],
)
def test_a_solid_is_the_one_its_written_curve_sweeps(
    shape: str, question: str, sweeps: bool
) -> None:
    assert revolves_into(shape, [question]) is sweeps


def test_a_curve_of_x_in_y_is_drawn_on_its_stated_interval() -> None:
    graph = _plot(
        "Revolve the region enclosed by the curve x = √y and the y-axis from y = 0 to y = 4.",
        {"item": "curve", "name": "f", "x": "sqrt(y)", "domain": ["0", "4"]},
    )
    assert graph is not None and graph.y_max >= 4
    ys = [y for segment in graph.curves[0].segments for _x, y in segment]
    assert max(ys) == pytest.approx(4, abs=1e-3)


@pytest.mark.parametrize(
    ("written", "value"),
    [
        ("0", 0.0),
        ("2π", 6.283185307),
        ("1/e", 0.367879441),
        ("e²", 7.389056099),
        ("−1", -1.0),
        ("−1/2", -0.5),
        ("3/2", 1.5),
        ("−3", -3.0),
        ("−4", -4.0),
        ("−π/2", -1.570796327),
        ("π/2", 1.570796327),
        ("2*pi", 6.283185307),
        (3, 3.0),
    ],
)
def test_a_range_end_is_read_as_the_question_writes_it(written: Any, value: float) -> None:
    """The figure read's 12 refusals of Unit 5 round 1, each value as the model sent it."""
    request = FigureRequest.model_validate({"kind": "function", "expr": "x", "x_min": written})
    assert request.x_min == pytest.approx(value)


def test_an_unreadable_range_end_is_left_out_not_the_reading() -> None:
    request = FigureRequest.model_validate(
        {"kind": "function", "expr": "x^2", "x_min": "the left end", "x_max": "∞"}
    )
    assert request.kind == "function" and request.x_min is None and request.x_max is None


@pytest.mark.parametrize(
    ("question", "items", "labels"),
    [
        (
            "Graph y = 2x + 1 and y = −x + 4 on the same axes and find where they meet.",
            [_curve("y", "2x + 1"), _curve("y", "-x + 4")],
            ["y = 2x + 1", "y = 4 − x"],
        ),
        (
            "Integrate 5/(2x) with respect to x, then sketch the members of the family of "
            "antiderivatives with c = −1, 0 and 1 on one graph.",
            [
                _curve("F(x)", "(5/2)*ln(abs(x)) - 1"),
                _curve("F(x)", "(5/2)*ln(abs(x))"),
                _curve("F(x)", "(5/2)*ln(abs(x)) + 1"),
            ],
            ["C = −1", "C = 0", "C = 1"],
        ),
    ],
)
def test_curves_named_alike_are_each_drawn(
    question: str, items: list[dict[str, Any]], labels: list[str]
) -> None:
    graph = _plot(question, *items)
    assert graph is not None and [curve.label for curve in graph.curves] == labels


def test_a_decimal_for_the_question_s_constant_is_that_constant() -> None:
    question = "Draw the graphs of k(x) = x² + 3x + π and g(x) = x² + 3x."
    graph = _plot(question, _curve("k", "x^2 + 3x + 3.14159"), _curve("g", "x^2 + 3x"))
    assert graph is not None and graph.curves[0].label == "y = x² + 3x + π"
    rough = _plot(question, _curve("k", "x^2 + 3x + 3.1"))
    assert rough is None or not rough.curves  # one place is no π


def test_a_line_written_in_latex_in_bold_is_written() -> None:
    working = (
        "The graph has a **vertical asymptote at $x = 2$** and a **horizontal one at $y = 0$**."
    )
    assert written_lines(working) == ((None, 2.0), (0.0, 0.0))


def test_a_curve_in_pieces_the_question_writes_whole_keeps_its_legend() -> None:
    graph = _plot(
        "Revolve the region enclosed by y = |x|, the x-axis and the lines x = −3 and x = 1.",
        _curve(
            "f", pieces=[{"y": "-x", "when": "-3 <= x <= 0"}, {"y": "x", "when": "0 <= x <= 1"}]
        ),
    )
    assert graph is not None and graph.curves[0].label == "y = |x|"


@pytest.mark.parametrize("axis", [_curve("g", "0"), {"item": "line", "name": "g", "y": "0"}])
def test_an_edge_described_as_y_equals_0_is_the_x_axis(axis: dict[str, Any]) -> None:
    # u5-071: the reply named the x-axis "g" (y = 0) and shaded between f and g.
    graph = _plot(
        "Revolve the region enclosed by y = |x|, the x-axis and the lines x = −3 and x = 1.",
        _curve(
            "f", pieces=[{"y": "-x", "when": "-3 <= x <= 0"}, {"y": "x", "when": "0 <= x <= 1"}]
        ),
        axis,
        _shade("f", "g", "-3", "1"),
    )
    assert graph is not None
    spans = sorted(
        (min(x for x, _ in r.points), max(x for x, _ in r.points)) for r in graph.regions
    )
    assert spans == [(-3.0, 0.0), (0.0, 1.0)]


def test_a_cylinder_read_for_a_paraboloid_is_not_drawn() -> None:
    """u5-083: the figure read drew x = √y about the y-axis as a cylinder of height 4."""
    import json

    from app.modules.math.figure.build import build_figure_fence

    question = (
        "Find the volume of the solid of revolution about the y-axis generated by revolving "
        "the region enclosed by the curve x = √y and the y-axis from y = 0 to y = 4. Sketch "
        "the region and the solid."
    )
    request = {
        "kind": "solid",
        "shape": "cylinder",
        "measures": [{"what": "height", "value": 4}],
    }
    assert build_figure_fence(json.dumps(request), [question]) is None
