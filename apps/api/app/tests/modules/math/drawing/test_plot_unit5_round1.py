"""Unit 5 round 1 (2026-11-16), the pictures: each class held where the round found it.

A region stands on the interval the question states (u5-051), a solid is the one the
written curve sweeps (u5-083), a range written as the question writes it is read (the
figure read's 12 refusals), curves named alike are all drawn (g04, u5-005, u5-008), a
decimal for the question's π is π (u5-001), a line written in LaTeX in bold is written
(g03), and a curve in pieces the question writes whole keeps its legend (u5-071).
"""

from __future__ import annotations

from typing import Any

import pytest

from app.modules.math.drawing.plot import written_lines
