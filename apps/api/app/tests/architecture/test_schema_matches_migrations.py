"""The ORM and the migrations describe the same schema (``alembic check``).

CI migrates the test database to head before the suite runs (locally,
``./scripts/dev.sh migrate``, or ``up``, which runs new migrations), so any
difference here is drift: a model changed without a migration, or a migration
the models don't reflect. An autogenerated migration would otherwise come out
wrong.
"""

from pathlib import Path

import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from alembic import command

_API_ROOT = Path(__file__).resolve().parents[3]


def test_models_match_the_migrated_schema() -> None:
    # No ini file: ``env.py`` would hand it to ``logging.config.fileConfig``, which
    # disables every logger already created and breaks ``caplog`` for the rest of
    # the run. ``script_location`` is the only setting the check needs.
    config = Config()
    config.set_main_option("script_location", str(_API_ROOT / "alembic"))
    try:
        command.check(config)
    except AutogenerateDiffsDetected as drift:
        pytest.fail(f"ORM and migrations disagree; add a migration or fix the model:\n{drift}")
