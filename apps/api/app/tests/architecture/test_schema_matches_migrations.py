"""The ORM and the migrations describe the same schema (``alembic check``).

The test database is migrated to head before the suite runs (CI and
``./scripts/dev.sh test-api``), so any difference here is drift: a model
changed without a migration, or a migration the models don't reflect. An
autogenerated migration would otherwise come out wrong.
"""

from pathlib import Path

import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from alembic import command

_API_ROOT = Path(__file__).resolve().parents[3]


def test_models_match_the_migrated_schema() -> None:
    config = Config(str(_API_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(_API_ROOT / "alembic"))
    try:
        command.check(config)
    except AutogenerateDiffsDetected as drift:
        pytest.fail(f"ORM and migrations disagree; add a migration or fix the model:\n{drift}")
